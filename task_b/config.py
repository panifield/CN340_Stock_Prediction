#
# ค่าที่เหมาะสมทางทฤษฎีคือ StdRatio = Rho (จุดที่ R2 สูงสุด = Rho^2)
# จึงตั้งเกณฑ์ตรวจรับเป็น StdRatio ลงมาอยู่ช่วง 0.10-0.20 ทั้งสองหุ้น
