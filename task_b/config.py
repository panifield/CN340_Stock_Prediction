# ค่าเดิม (64, 32) + alpha 1e-3 ทำให้โมเดล overfit หนัก:
#   R2_return = -2.34 (KBANK) และ -1.95 (ADVANC)
#
# แต่ตัวเลขติดลบมหาศาลนั้น "ไม่ได้" แปลว่าโมเดลไม่มีทักษะ เพราะ R2
# แตกออกได้เป็น  R2 = 2*Rho*StdRatio - StdRatio^2 - Bias^2
# ค่าเดิมมี StdRatio = 1.63 -> พจน์ -StdRatio^2 = -2.65 เพียงพจน์เดียว
# คิดเป็นราว 90% ของ R2 ที่ติดลบทั้งหมด
# => ปัญหาคือ "ทำนายแกว่งกว้างเกินจริง 16 เท่า" ไม่ใช่ "ทายผิดทิศ"
#
# ค่าที่เหมาะสมทางทฤษฎีคือ StdRatio = Rho (จุดที่ R2 สูงสุด = Rho^2)
# จึงตั้งเกณฑ์ตรวจรับเป็น StdRatio ลงมาอยู่ช่วง 0.10-0.20 ทั้งสองหุ้น
#
# กวาด 4 ขนาด x 5 alpha x 2 solver = 80 ชุด แล้วกวาดละเอียดอีก 18 ชุด
# ในช่วง alpha 1-10 (มีหน้าผาชันตรงนั้น) สรุปได้ว่า:
#   - alpha คือตัวแปรหลัก ไม่ใช่ขนาดของ network
#   - alpha >= 100 ทำให้โมเดลยุบเป็นค่าคงที่ (StdRatio = 0) ซึ่ง MAE ดู
#     ดีที่สุดแต่กลายเป็น Mean Return baseline ที่ใส่ neural network ครอบ
#   - solver="lbfgs" ให้ StdRatio สูงกว่าและ MAE แย่กว่า adam ทุกจุด
#     อีกทั้งไม่มี loss_curve_ ให้ทำกราฟ (เป็น full-batch) จึงไม่เลือก
#
# กฎการเลือก (ประกาศก่อนดูผล): ในบรรดาชุดที่ StdRatio อยู่ใน 0.10-0.20
# ทั้งสองหุ้น เลือกตัวที่ MAE_return เฉลี่ยต่ำสุด เสมอกันเลือกตัวเล็กกว่า
